// Generate React Native components from the exported SVGs.
//
// Sibling of `build-react.mjs`: same `icons/` sources, a different primitive
// set (`react-native-svg` instead of DOM `<svg>`). The web modules stay
// byte-identical because this file never writes them. Run after `icons:build`.
//
//   node pipeline/build-react-native.mjs [--check]
//
// --check writes nothing and exits non-zero if the output would differ, the
// same contract `build-react.mjs --check` offers for the web package.

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises"
import { existsSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const SRC = join(ROOT, "packages", "react-native", "src")

/**
 * One entry per generated named module. `corners: "regular"` is the rounded
 * treatment on disk (`icons/<style>/`); the public `KeylineIcon` prop is
 * `"rounded"`, because that is the word the API uses. `"sharp"` is the same
 * word on both sides.
 *
 * Filenames match the web package so the eight `exports` paths can stay
 * identical: `/sharp/two-tone` still resolves to `sharp-two-tone`.
 */
const MODULES = [
  { style: "stroke", corners: "regular", file: "index.tsx", ns: "StrokeRounded" },
  { style: "two-tone", corners: "regular", file: "two-tone.tsx", ns: "TwoToneRounded" },
  { style: "duotone", corners: "regular", file: "duotone.tsx", ns: "DuotoneRounded" },
  { style: "fill", corners: "regular", file: "fill.tsx", ns: "FillRounded" },
  { style: "stroke", corners: "sharp", file: "sharp.tsx", ns: "StrokeSharp" },
  { style: "two-tone", corners: "sharp", file: "sharp-two-tone.tsx", ns: "TwoToneSharp" },
  { style: "duotone", corners: "sharp", file: "sharp-duotone.tsx", ns: "DuotoneSharp" },
  { style: "fill", corners: "sharp", file: "sharp-fill.tsx", ns: "FillSharp" },
]

const RN_TAGS = {
  path: "Path",
  circle: "Circle",
  rect: "Rect",
  line: "Line",
  polyline: "Polyline",
  polygon: "Polygon",
  ellipse: "Ellipse",
}

const check = process.argv.includes("--check")

const c = (n, s) => `\x1b[${n}m${s}\x1b[0m`

/** Attributes the wrapper supplies itself, so they must not be re-emitted. */
const ROOT_DROP = new Set(["width", "height", "xmlns", "viewBox"])

/**
 * kebab-case SVG attribute -> React prop name, read from `components/glyph.tsx`
 * rather than written out again here. Same source `build-react.mjs` trusts, so
 * a mapping added for the web package cannot go missing on the RN side.
 */
const CAMEL = Object.fromEntries(
  [
    ...(await readFile(join(ROOT, "components", "glyph.tsx"), "utf8")).matchAll(
      /"([a-z]+-[a-z-]+)":\s*"([a-zA-Z]+)"/g
    ),
  ].map(([, kebab, prop]) => [kebab, prop])
)

if (!CAMEL["fill-opacity"] || !CAMEL["stroke-opacity"]) {
  throw new Error(
    "REACT_ATTR in components/glyph.tsx no longer parses: the opacity mappings are missing"
  )
}

const ATTR = /([\w-]+)="([^"]*)"/g
const TAG = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g

const attrs = (chunk) => [...chunk.matchAll(ATTR)].map(([, k, v]) => [k, v])

const pascal = (name) =>
  name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")

/** Numeric-looking attribute values become JSX expressions, like lucide's. */
function jsxValue(value) {
  return /^-?\d+(\.\d+)?$/.test(value) ? `{${value}}` : `"${value}"`
}

function jsxAttrs(pairs) {
  return pairs.map(([k, v]) => ` ${CAMEL[k] ?? k}=${jsxValue(v)}`).join("")
}

const apiCorners = (corners) => (corners === "sharp" ? "sharp" : "rounded")

/**
 * The wrapper is emitted into every module rather than imported from a shared
 * one. Same reason as the web generator: importing
 * `@keyline-icons/react-native/fill` pulls in that file and nothing else.
 */
const header = (dir) => `// GENERATED BY pipeline/build-react-native.mjs — DO NOT EDIT.
// Source: ${dir}/*.svg. Regenerate with \`pnpm icons:react-native\`.

import type { ReactNode } from "react"
import Svg, { Path, Circle, Rect, Line, Polyline, Polygon, Ellipse, type SvgProps } from "react-native-svg"

export type IconProps = Omit<SvgProps, "children"> & {
  size?: number | string
  color?: string
  strokeWidth?: number | string
}

function Icon({ size = 24, color, strokeWidth, children, ...props }: IconProps & { children?: ReactNode }) {
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24" color={color} strokeWidth={strokeWidth} {...props}>
      {children}
    </Svg>
  )
}
`

/** One module's full text, plus how many components it carries and their kebab names. */
async function build(style, corners) {
  const rel = corners === "sharp" ? `icons/sharp/${style}` : `icons/${style}`
  const dir = join(ROOT, rel)
  const files = (await readdir(dir)).filter((f) => f.endsWith(".svg")).sort()

  const components = []
  const names = []
  for (const file of files) {
    const name = file.slice(0, -4)
    names.push(name)
    const src = await readFile(join(dir, file), "utf8")

    const open = src.match(/<svg\b([^>]*)>/)?.[1] ?? ""
    const root = attrs(open).filter(([k]) => !ROOT_DROP.has(k))

    const body = [...src.matchAll(TAG)]
      .map(([, tag, chunk]) => {
        const rn = RN_TAGS[tag]
        if (!rn) {
          throw new Error(`unmapped SVG tag <${tag}> in ${rel}/${file}`)
        }
        return `      <${rn}${jsxAttrs(attrs(chunk))} />`
      })
      .join("\n")

    components.push(
      `export function ${pascal(name)}(props: IconProps) {\n` +
        `  return (\n` +
        `    <Icon${jsxAttrs(root)} {...props}>\n` +
        `${body}\n` +
        `    </Icon>\n` +
        `  )\n` +
        `}`
    )
  }

  return {
    text: `${header(rel)}\n${components.join("\n\n")}\n`,
    count: components.length,
    rel,
    names,
  }
}

function buildIcon(built) {
  const imports = built
    .map((m) => `import * as ${m.ns} from "./${m.file.replace(/\.tsx$/, "")}"`)
    .join("\n")

  const styles = ["stroke", "two-tone", "duotone", "fill"]
  const cornerKeys = ["rounded", "sharp"]

  const styleBlocks = styles.map((style) => {
    const cornerBlocks = cornerKeys.map((corner) => {
      const mod = built.find(
        (m) => m.style === style && apiCorners(m.corners) === corner
      )
      const entries = mod.names
        .map((name) => `      "${name}": ${mod.ns}.${pascal(name)},`)
        .join("\n")
      return `    ${corner}: {\n${entries}\n    }`
    })
    return `  ${JSON.stringify(style)}: {\n${cornerBlocks.join(",\n")},\n  }`
  })

  return `// GENERATED BY pipeline/build-react-native.mjs — DO NOT EDIT.
// Full cross-style registry for KeylineIcon. Importing this module loads every
// style; prefer named imports from a style entry point when the icon is known
// at build time.

import type { ComponentType } from "react"
import type { IconProps } from "./index"
${imports}

declare const __DEV__: boolean | undefined

export type IconStyle = "stroke" | "two-tone" | "duotone" | "fill"
export type Corners = "rounded" | "sharp"

export type { IconProps }

type IconComponent = ComponentType<IconProps>

const REGISTRY: Record<IconStyle, Record<Corners, Record<string, IconComponent>>> = {
${styleBlocks.join(",\n")},
}

export type KeylineIconProps = IconProps & {
  name: string
  iconStyle?: IconStyle
  corners?: Corners
}

function KeylineIcon({ name, iconStyle = "stroke", corners = "rounded", ...props }: KeylineIconProps) {
  const Comp = REGISTRY[iconStyle]?.[corners]?.[name]
  if (!Comp) {
    if (typeof __DEV__ !== "undefined" && __DEV__) {
      console.warn(\`[KeylineIcon] unknown icon: name=\${name} iconStyle=\${iconStyle} corners=\${corners}\`)
    }
    return null
  }
  return <Comp {...props} />
}

export default KeylineIcon
export { KeylineIcon }
`
}

const built = []
for (const mod of MODULES) built.push({ ...mod, ...(await build(mod.style, mod.corners)) })

const iconText = buildIcon(built)
const targets = [
  ...built.map((m) => ({
    label: `packages/react-native/src/${m.file}`,
    path: join(SRC, m.file),
    text: m.text,
    rel: m.rel,
  })),
  {
    label: "packages/react-native/src/icon.tsx",
    path: join(SRC, "icon.tsx"),
    text: iconText,
    rel: "icons/",
  },
]

if (check) {
  // Every target is reported before exiting. Same reason as build-react.mjs:
  // bailing on the first hides a second stale module behind the one that
  // happens to sort earlier.
  let drift = false
  for (const { label, path, text, rel } of targets) {
    const prev = existsSync(path) ? await readFile(path, "utf8") : null
    if (prev === text) continue
    const why = prev === null ? "does not exist" : `is out of sync with ${rel}/`
    console.error(`  ${c(33, "DRIFT")} ${label} ${why}`)
    drift = true
  }
  if (drift) {
    console.error(`\nRun: node pipeline/build-react-native.mjs`)
    process.exit(1)
  }
  const summary = built
    .map((m) => `${m.corners === "sharp" ? "sharp " : ""}${m.style} ${m.count}`)
    .join(", ")
  console.log(
    c(32, `${targets.length} generated modules in sync with icons/ (${summary})`)
  )
} else {
  await mkdir(SRC, { recursive: true })
  for (const { path, text } of targets) {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, text, "utf8")
  }
  for (const m of built) {
    console.log(`Wrote ${m.count} components to packages/react-native/src/${m.file}`)
  }
  console.log(`Wrote KeylineIcon registry to packages/react-native/src/icon.tsx`)
}
